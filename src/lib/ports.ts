export function searchPorts(q: string): Port[] {  const s = q.trim().toLowerCase();
  if (s.length < 2) return [];
  const starts: Port[] = [];
  const contains: Port[] = [];
  for (const p of PORTS) {
    const hay = `${p.name} ${p.code} ${p.country}`.toLowerCase();
    if (!hay.includes(s)) continue;
    if (p.name.toLowerCase().startsWith(s) || p.code.toLowerCase().startsWith(s.toUpperCase())) starts.push(p);
    else contains.push(p);
  }
  return [...starts, ...contains].slice(0, 20);
}

