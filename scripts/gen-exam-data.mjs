// SoruHavuzu/*.json -> web/src/lib/exam-data/<rank>.ts (per-rank chunks,
// dynamic import ile sayfada lazy yüklenir) + index.ts (rank/ders sayımları).
// Usage: node web/scripts/gen-exam-data.mjs [havuzDir] [outDir]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const havuz = process.argv[2] ?? "C:\\Users\\furka\\Desktop\\Projects\\Officer Asistant\\SoruHavuzu";
const outDir = process.argv[3] ?? path.join(here, "..", "src", "lib", "exam-data");

const trMap = { ç: "c", ğ: "g", ı: "i", ö: "o", ş: "s", ü: "u", İ: "i", Ç: "c", Ğ: "g", Ö: "o", Ş: "s", Ü: "u" };
const slugify = (s) => s.toLowerCase().replace(/[çğıöşüİÇĞÖŞÜ]/g, (c) => trMap[c] ?? "").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
const pretty = (s) => s.replace(/-/g, " ");

fs.mkdirSync(outDir, { recursive: true });

const ranks = [];
const skipped = { stem: 0, opt: 0 };
for (const rankDir of fs.readdirSync(havuz, { withFileTypes: true })) {
  if (!rankDir.isDirectory()) continue;
  const rankKey = rankDir.name;
  const rankAd = pretty(rankKey);
  const slug = slugify(rankKey);
  const denemeler = [];
  for (const dersDir of fs.readdirSync(path.join(havuz, rankKey), { withFileTypes: true })) {
    if (!dersDir.isDirectory()) continue;
    const dersAd = pretty(dersDir.name);
    for (const f of fs.readdirSync(path.join(havuz, rankKey, dersDir.name))) {
      const m = f.match(/^deneme-(\d+)\.json$/);
      if (!m) continue;
      const j = JSON.parse(fs.readFileSync(path.join(havuz, rankKey, dersDir.name, f), "utf8"));
      const sorular = [];
      for (const s of (Array.isArray(j) ? j : j.sorular)) {
        const stem = String(s.soru ?? "").trim();
        if (!stem) { skipped.stem++; continue; } // stem not scraped — drop, never fabricate
        const siklar = [0, 1, 2, 3, 4].map((i) => {
          const o = String(s.siklar[i] ?? "").trim();
          if (!o) skipped.opt++;
          return o || "—"; // blank option in source; letters + answer key preserved
        });
        const cevap = s.cevap == null ? null : Number(s.cevap);
        if (!(cevap === null || (cevap >= 1 && cevap <= 5))) {
          throw new Error(`bozuk cevap: ${rankKey}/${dersDir.name}/${f} no${s.no}`);
        }
        sorular.push({ no: s.no, soru: stem, gorsel: Array.isArray(s.gorsel) ? s.gorsel.map(String) : [], siklar, cevap });
      }
      denemeler.push({ rank: rankAd, ders: dersAd, deneme: Number(m[1]), kaynak_url: j.kaynak_url ?? "", soru_sayisi: sorular.length, sorular });
    }
  }
  denemeler.sort((a, b) => (a.ders < b.ders ? -1 : a.ders > b.ders ? 1 : a.deneme - b.deneme));
  const dersMap = new Map();
  for (const d of denemeler) {
    const e = dersMap.get(d.ders) ?? { ad: d.ders, deneme: 0, soru: 0 };
    e.deneme++;
    e.soru += d.sorular.length;
    dersMap.set(d.ders, e);
  }
  const ts =
    `import type { HavuzDeneme } from "../exams";\n\n` +
    `// AUTO-GENERATED from SoruHavuzu/${rankKey} by web/scripts/gen-exam-data.mjs. Do not edit.\n` +
    `export const RANK_SLUG = ${JSON.stringify(slug)};\nexport const RANK_ADI = ${JSON.stringify(rankAd)};\n` +
    `export const DENEMELER: HavuzDeneme[] = ${JSON.stringify(denemeler)};\n`;
  fs.writeFileSync(path.join(outDir, `${slug}.ts`), ts, "utf8");
  const soru = denemeler.reduce((a, d) => a + d.sorular.length, 0);
  ranks.push({ slug, ad: rankAd, deneme: denemeler.length, soru, dersler: [...dersMap.values()] });
  console.log(`${slug}: ${denemeler.length} deneme, ${soru} soru`);
}

ranks.sort((a, b) => b.soru - a.soru);
const idx =
  `// AUTO-GENERATED by web/scripts/gen-exam-data.mjs. Do not edit.\n` +
  `export interface ExamDersMeta { ad: string; deneme: number; soru: number }\n` +
  `export interface ExamRankMeta { slug: string; ad: string; deneme: number; soru: number; dersler: ExamDersMeta[] }\n` +
  `export const EXAM_RANKS: ExamRankMeta[] = ${JSON.stringify(ranks, null, 1)};\n` +
  `export const EXAM_TOPLAM_SORU = ${ranks.reduce((a, r) => a + r.soru, 0)};\n` +
  `export const EXAM_TOPLAM_DENEME = ${ranks.reduce((a, r) => a + r.deneme, 0)};\n`;
fs.writeFileSync(path.join(outDir, "index.ts"), idx, "utf8");
console.log(`toplam: ${ranks.reduce((a, r) => a + r.soru, 0)} soru, ${ranks.reduce((a, r) => a + r.deneme, 0)} deneme (atlanan: ${skipped.stem} stemsiz, ${skipped.opt} bos sik)`);
